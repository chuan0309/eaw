def load_archive():
    if os.path.exists(ARCHIVE_FILE):
        try:
            with open(ARCHIVE_FILE, 'r', encoding='utf-8') as f:
                data = json.load(f)
                if isinstance(data, list):
                    return data
        except Exception as e:
            print(f"[!] 讀取 {ARCHIVE_FILE} 失敗: {e}")
    return []

def save_archive(data):
    with open(ARCHIVE_FILE, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

def compute_coord(base_lat, base_lng, seed_str):
    h = int(hashlib.md5(seed_str.encode('utf-8')).hexdigest()[:8], 16)
    lat_offset = (((h & 0xFFFF) / 65535.0) - 0.5) * 0.016
    lng_offset = ((((h >> 16) & 0xFFFF) / 65535.0) - 0.5) * 0.016
    return round(base_lat + lat_offset, 5), round(base_lng + lng_offset, 5)

def fetch_japan_google_news_rss(pref, dist):
    """查詢日本 Google News RSS 最新事故物件/事件新聞"""
    query = f"{pref} {dist} (マンション OR アパート OR 住宅) (死亡 OR 遺体 OR 事件 OR 火災)"
    url = f"https://news.google.com/rss/search?q={urllib.parse.quote(query)}&hl=ja&gl=JP&ceid=JP:ja"
    results = []
    try:
        resp = requests.get(url, timeout=8, headers={"User-Agent": "Mozilla/5.0"})
        if resp.status_code == 200:
            root = ET.fromstring(resp.content)
            for item in root.findall('.//item')[:2]:
                title = item.findtext('title') or ''
                pub_date = item.findtext('pubDate') or ''
                if title:
                    results.append((title, pub_date))
    except Exception:
        pass
    return results

