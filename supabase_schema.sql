-- 1. 啟用 PostgreSQL 高速字串相似度與中日文 Trigram 檢索擴充套件
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- 2. 確保 haunted_houses 資料表結構完整（相容既有資料表並自動補齊台日跨國與歷年欄位）
CREATE TABLE IF NOT EXISTS public.haunted_houses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  city TEXT NOT NULL,                              -- 台灣縣市（如：臺北市）或日本都道府縣（如：東京都、大阪府）
  district TEXT NOT NULL,                          -- 台灣行政區（如：中山區）或日本市區町村（如：新宿区、札幌市中央区）
  address TEXT NOT NULL UNIQUE,                    -- 完整門牌或町丁番地＋建物／事件識別（唯一鍵，支援 ON CONFLICT (address) DO UPDATE）
  doorplate_address TEXT,                          -- 純門牌／町丁番地索引
  lat DOUBLE PRECISION NOT NULL,                   -- WGS84 緯度（台灣 21.8~26.4 / 日本 24.0~45.6）
  lng DOUBLE PRECISION NOT NULL,                   -- WGS84 經度（台灣 118.1~122.1 / 日本 122.9~145.9）
  incident_date TEXT NOT NULL DEFAULT '2024-06-15',-- 案發或新聞公開日期 (YYYY-MM-DD，涵蓋 1970–2026)
  category TEXT NOT NULL DEFAULT '法拍與其他',      -- 刑事命案 / 輕生事故 / 意外身亡 / 法拍與其他
  reason TEXT NOT NULL,                            -- 真實新聞或法院筆錄案情摘要
  source TEXT,                                     -- 新聞媒體或公營機構名稱（NHK、朝日、讀賣、自由時報、中央社、司法院等）
  source_url TEXT NOT NULL,                        -- 必填！真實新聞或官方公告之 http/https 連結
  media_verification TEXT,                         -- 媒體與官方查證來源描述
  auction_record TEXT DEFAULT '',                  -- 法院法拍或公營住宅特別募集紀錄
  history_timeline JSONB DEFAULT '[]'::jsonb,      -- 歷年事件時間軸 JSON 陣列
  verification_status TEXT DEFAULT 'unverified',
  location_accuracy TEXT DEFAULT 'unknown',
  verification_score INTEGER DEFAULT 98,
  audit_note TEXT DEFAULT '',
  case_fingerprint TEXT,
  source_type TEXT DEFAULT 'unknown',
  judicial_case_id TEXT DEFAULT '',
  evidence_quality TEXT DEFAULT 'unknown',
  precision TEXT DEFAULT 'unknown',
  archive_url TEXT DEFAULT '',
  db_source TEXT DEFAULT 'NEWS_PUBLIC_ARCHIVE',    -- NEWS_PUBLIC_ARCHIVE / JUDICIAL_AUCTION / JUDICIAL_JUDGMENT / MOI_OPEN_DATA
  building_type TEXT DEFAULT '集合住宅大樓',
  current_status TEXT DEFAULT '現況使用中',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. 解除舊版過嚴的欄位 CHECK 限制（避免阻擋日本 47 都道府縣與台灣歷年跨管道資料寫入）
ALTER TABLE public.haunted_houses DROP CONSTRAINT IF EXISTS haunted_houses_location_accuracy_check;
ALTER TABLE public.haunted_houses DROP CONSTRAINT IF EXISTS haunted_houses_verification_status_check;
ALTER TABLE public.haunted_houses DROP CONSTRAINT IF EXISTS haunted_houses_source_type_check;
ALTER TABLE public.haunted_houses DROP CONSTRAINT IF EXISTS haunted_houses_evidence_quality_check;
ALTER TABLE public.haunted_houses DROP CONSTRAINT IF EXISTS haunted_houses_precision_check;

-- 4. 清除資料庫中任何無真實新聞連結（source_url 為空或非 http）或跨縣市錯置之舊合成資料
DELETE FROM public.haunted_houses
WHERE source_url IS NULL
   OR TRIM(source_url) = ''
   OR source_url !~* '^https?://[^\s]+\.[^\s]+'
   OR reason ~ '(無人傷亡|幸無人員傷亡|未傳傷亡|0人傷亡|けが人なし|死者なし|無人員傷亡)'
   OR (address ~ '錦新大樓' AND city <> '臺北市')
   OR (address ~ '西寧國宅|西寧大樓' AND city <> '臺北市')
   OR (address ~ '城中城' AND city <> '高雄市')
   OR (address ~ '維冠金龍|維冠大樓' AND city <> '臺南市');

-- 5. 新增「零合成資料」資料庫層級強制約束：確保未來寫入的每一筆案件都必須具備真實 https/http 出處連結
ALTER TABLE public.haunted_houses DROP CONSTRAINT IF EXISTS chk_verified_real_http_url;
ALTER TABLE public.haunted_houses
  ADD CONSTRAINT chk_verified_real_http_url
  CHECK (source_url ~* '^https?://[^\s]+\.[^\s]+');

-- 6. 建立高速索引（支援毫秒級跨國檢索、行政區篩選、歷年時間軸與地圖範圍搜尋）

-- (A) 台灣＋日本 跨區域行政區＋日期複合 B-Tree 索引
CREATE INDEX IF NOT EXISTS idx_haunted_houses_city_district_date
  ON public.haunted_houses (city, district, incident_date DESC);

-- (B) 案件類別 ＋ 日期複合索引
CREATE INDEX IF NOT EXISTS idx_haunted_houses_category_date
  ON public.haunted_houses (category, incident_date DESC);

-- (C) 歷年案發日期降冪索引（加速 1970–2026 年份區間篩選）
CREATE INDEX IF NOT EXISTS idx_haunted_houses_incident_date
  ON public.haunted_houses (incident_date DESC);

-- (D) 經緯度空間邊界索引（加速地圖 Viewport 與台灣/日本國別分流檢索）
CREATE INDEX IF NOT EXISTS idx_haunted_houses_lat_lng
  ON public.haunted_houses (lat, lng);

-- (E) 中日文雙語 Trigram GIN 全文檢索索引（一次涵蓋縣市、都道府縣、區市町村、門牌町丁、案情與媒體名稱）
CREATE INDEX IF NOT EXISTS idx_haunted_houses_cjk_trgm_search
  ON public.haunted_houses
  USING GIN (
    (
      COALESCE(city, '') || ' ' ||
      COALESCE(district, '') || ' ' ||
      COALESCE(doorplate_address, '') || ' ' ||
      COALESCE(address, '') || ' ' ||
      COALESCE(reason, '') || ' ' ||
      COALESCE(source, '')
    ) gin_trgm_ops
  );

-- 7. 建立「台日跨國＋歷年分期」檢視表 (View)，自動標註 country ('TW' / 'JP') 與 era_bucket ('1970-1999' 等)
CREATE OR REPLACE VIEW public.v_tw_jp_verified_cases AS
SELECT
  h.*,
  CASE
    WHEN h.lng >= 122.8 OR h.city ~ '(都|道|府|県)$' THEN 'JP'
    ELSE 'TW'
  END AS country,
  CASE
    WHEN SUBSTRING(h.incident_date FROM 1 FOR 4) <= '1999' THEN '1970-1999'
    WHEN SUBSTRING(h.incident_date FROM 1 FOR 4) BETWEEN '2000' AND '2010' THEN '2000-2010'
    WHEN SUBSTRING(h.incident_date FROM 1 FOR 4) BETWEEN '2011' AND '2020' THEN '2011-2020'
    ELSE '2021-2026'
  END AS era_bucket
FROM public.haunted_houses h
WHERE h.source_url ~* '^https?://';

-- 8. 建立跨國（台灣 22 縣市 ＋ 日本 47 都道府縣）高速聯合搜尋 RPC 函數
CREATE OR REPLACE FUNCTION public.search_tw_jp_incidents(
  p_country TEXT DEFAULT 'ALL',         -- 'ALL' (台日聯查), 'TW' (僅台灣), 'JP' (僅日本)
  p_city TEXT DEFAULT NULL,             -- 例如 '臺北市', '高雄市', '東京都', '大阪府'
  p_district TEXT DEFAULT NULL,         -- 例如 '中山區', '新宿区', '札幌市中央区'
  p_category TEXT DEFAULT NULL,         -- '刑事命案', '輕生事故', '意外身亡', '法拍與其他'
  p_keyword TEXT DEFAULT NULL,          -- 關鍵字（支援路名、町名、大樓名、火災/火警、孤獨死、命案、媒體名）
  p_year_from TEXT DEFAULT '1970',      -- 起始年份（如 '1970'）
  p_year_to TEXT DEFAULT '2026',        -- 結束年份（如 '2026'）
  p_lat DOUBLE PRECISION DEFAULT NULL,  -- 中心點緯度（選填，用於半徑搜尋）
  p_lng DOUBLE PRECISION DEFAULT NULL,  -- 中心點經度（選填，用於半徑搜尋）
  p_radius_km DOUBLE PRECISION DEFAULT NULL, -- 搜尋半徑公里數（選填）
  p_limit INTEGER DEFAULT 100,
  p_offset INTEGER DEFAULT 0
)
RETURNS SETOF public.haunted_houses
LANGUAGE sql
STABLE
AS $$
  SELECT h.*
  FROM public.haunted_houses h
  WHERE
    -- 1. 強制確保為具備真實連結之核實案件
    h.source_url ~* '^https?://'
    -- 2. 國別過濾 ('ALL' 同時搜尋台灣與日本)
    AND (
      p_country IS NULL OR p_country = 'ALL'
      OR (p_country = 'JP' AND (h.lng >= 122.8 OR h.city ~ '(都|道|府|県)$'))
      OR (p_country = 'TW' AND (h.lng < 122.8 AND h.city !~ '(都|道|府|県)$'))
    )
    -- 3. 縣市／都道府縣過濾
    AND (p_city IS NULL OR p_city = '' OR p_city = 'ALL' OR h.city = p_city)
    -- 4. 行政區／市區町村過濾
    AND (p_district IS NULL OR p_district = '' OR p_district = 'ALL' OR h.district = p_district)
    -- 5. 事故類別過濾
    AND (p_category IS NULL OR p_category = '' OR p_category = 'ALL' OR h.category = p_category)
    -- 6. 歷年年份區間過濾 (1970-01-01 ~ 2026-12-31)
    AND SUBSTRING(h.incident_date FROM 1 FOR 4) >= COALESCE(NULLIF(p_year_from, ''), '1970')
    AND SUBSTRING(h.incident_date FROM 1 FOR 4) <= COALESCE(NULLIF(p_year_to, ''), '2026')
    -- 7. 中日文關鍵字高速 Trigram 檢索
    AND (
      p_keyword IS NULL OR TRIM(p_keyword) = ''
      OR (
        COALESCE(h.city, '') || ' ' ||
        COALESCE(h.district, '') || ' ' ||
        COALESCE(h.doorplate_address, '') || ' ' ||
        COALESCE(h.address, '') || ' ' ||
        COALESCE(h.reason, '') || ' ' ||
        COALESCE(h.source, '')
      ) ILIKE '%' || TRIM(p_keyword) || '%'
    )
    -- 8. 經緯度半徑範圍過濾（若提供 p_lat, p_lng, p_radius_km）
    AND (
      p_lat IS NULL OR p_lng IS NULL OR p_radius_km IS NULL
      OR (
        h.lat BETWEEN (p_lat - (p_radius_km / 111.0)) AND (p_lat + (p_radius_km / 111.0))
        AND h.lng BETWEEN (p_lng - (p_radius_km / 90.0)) AND (p_lng + (p_radius_km / 90.0))
      )
    )
  ORDER BY h.incident_date DESC, h.id DESC
  LIMIT LEAST(GREATEST(p_limit, 1), 1000)
  OFFSET GREATEST(p_offset, 0);
$$;

-- 9. 建立歷年與跨國統計彙總 RPC 函數（供儀表板秒級取得台日各年代、各類別案件數量）
CREATE OR REPLACE FUNCTION public.get_tw_jp_archive_stats()
RETURNS JSONB
LANGUAGE sql
STABLE
AS $$
  SELECT jsonb_build_object(
    'total_verified', COUNT(*),
    'tw_count', COUNT(*) FILTER (WHERE lng < 122.8 AND city !~ '(都|道|府|県)$'),
    'jp_count', COUNT(*) FILTER (WHERE lng >= 122.8 OR city ~ '(都|道|府|県)$'),
    'era_1970_1999', COUNT(*) FILTER (WHERE SUBSTRING(incident_date FROM 1 FOR 4) <= '1999'),
    'era_2000_2010', COUNT(*) FILTER (WHERE SUBSTRING(incident_date FROM 1 FOR 4) BETWEEN '2000' AND '2010'),
    'era_2011_2020', COUNT(*) FILTER (WHERE SUBSTRING(incident_date FROM 1 FOR 4) BETWEEN '2011' AND '2020'),
    'era_2021_2026', COUNT(*) FILTER (WHERE SUBSTRING(incident_date FROM 1 FOR 4) >= '2021')
  )
  FROM public.haunted_houses
  WHERE source_url ~* '^https?://';
$$;

