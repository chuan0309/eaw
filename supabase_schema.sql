-- =============================================================================
-- 台灣 22 縣市 + 日本 47 都道府縣 跨國歷年事故建物與實證資料庫 (Supabase PostgreSQL)
-- 檔案：supabase_schema.sql
-- 包含四大核心資料表：
--   1. public.cases (與 public.haunted_houses 雙向相容之案件主表)
--   2. public.case_sources (一對多案件原始新聞／判決／法拍證據來源表)
--   3. public.pending_cases (地址模糊或待人工／二次查證之隔離資料表，不直接公開)
--   4. public.crawl_logs (自動化爬蟲執行紀錄表)
-- =============================================================================

-- 1. 啟用 PostgreSQL 高速字串相似度與中日文 Trigram 檢索擴充套件
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- 2. 案件主表：public.haunted_houses（相容既有前端與 API）並新增 country 等完整查證欄位
CREATE TABLE IF NOT EXISTS public.haunted_houses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  country TEXT NOT NULL DEFAULT 'TW',              -- 國別：'TW' (Taiwan) 或 'JP' (Japan)
  city TEXT NOT NULL,                              -- 台灣縣市（如：臺北市）或日本都道府縣（如：東京都、大阪府）
  district TEXT NOT NULL,                          -- 台灣行政區（如：中山區）或日本市區町村（如：新宿区、横浜市港北区）
  address TEXT NOT NULL UNIQUE,                    -- 標準化完整門牌／町丁番地＋建物型態（唯一鍵）
  doorplate_address TEXT,                          -- 純門牌／町丁番地標準化索引（去重與正規化比對用）
  lat DOUBLE PRECISION NOT NULL,                   -- WGS84 緯度（台灣 21.8~26.4 / 日本 24.0~45.6）
  lng DOUBLE PRECISION NOT NULL,                   -- WGS84 經度（台灣 118.1~122.1 / 日本 122.9~145.9）
  incident_date TEXT NOT NULL DEFAULT '2024-06-15',-- 事故發生或新聞公開日期 (YYYY-MM-DD，涵蓋歷史至最新)
  category TEXT NOT NULL DEFAULT '法拍與其他',      -- 刑事命案 / 輕生事故 / 意外身亡 / 其他非自然死亡 / 法拍與其他
  reason TEXT NOT NULL,                            -- 真實新聞、法院裁判書或法拍筆錄之案件摘要
  source TEXT,                                     -- 主要資料來源名稱（如：自由時報、中央社、司法院、NHK、朝日新聞等）
  source_url TEXT NOT NULL,                        -- 主要原始資料網址（必填 https/http）
  source_title TEXT DEFAULT '',                    -- 原始報導或公告標題
  media_verification TEXT,                         -- 多來源查證描述
  auction_record TEXT DEFAULT '',                  -- 法院法拍筆錄或日本公營住宅特別募集紀錄
  history_timeline JSONB DEFAULT '[]'::jsonb,      -- 歷年事件時間軸與多方來源整併紀錄
  verification_status TEXT DEFAULT 'verified',     -- verified / multi_source_verified
  location_accuracy TEXT DEFAULT 'ROOFTOP',        -- ROOFTOP / STREET_LEVEL / CHOME_LEVEL
  verification_score INTEGER DEFAULT 95,
  audit_note TEXT DEFAULT '',
  case_fingerprint TEXT,                           -- 案件去重指紋 (country + city + district + normalized_road + date_ym + category)
  source_type TEXT DEFAULT 'news',                 -- news / judicial_judgment / judicial_auction / government_open_data
  judicial_case_id TEXT DEFAULT '',
  evidence_quality TEXT DEFAULT 'high',
  precision TEXT DEFAULT 'street',
  archive_url TEXT DEFAULT '',
  db_source TEXT DEFAULT 'NEWS_PUBLIC_ARCHIVE',    -- NEWS_PUBLIC_ARCHIVE / JUDICIAL_AUCTION / JUDICIAL_JUDGMENT / MOI_OPEN_DATA
  building_type TEXT DEFAULT '集合住宅大樓',
  current_status TEXT DEFAULT '現況使用中',
  merged_count INTEGER DEFAULT 1,                  -- 同一事故合併之獨立新聞／官方來源數量
  collected_at TIMESTAMPTZ DEFAULT NOW(),          -- 資料首次蒐集時間
  updated_at TIMESTAMPTZ DEFAULT NOW(),            -- 資料最後更新時間
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 補齊既有資料表可能缺少的欄位（無損升級）
ALTER TABLE public.haunted_houses ADD COLUMN IF NOT EXISTS country TEXT NOT NULL DEFAULT 'TW';
ALTER TABLE public.haunted_houses ADD COLUMN IF NOT EXISTS source_title TEXT DEFAULT '';
ALTER TABLE public.haunted_houses ADD COLUMN IF NOT EXISTS merged_count INTEGER DEFAULT 1;
ALTER TABLE public.haunted_houses ADD COLUMN IF NOT EXISTS collected_at TIMESTAMPTZ DEFAULT NOW();
ALTER TABLE public.haunted_houses ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ DEFAULT NOW();

-- 自動修正既有資料的 country 欄位（明確區分 TW 與 JP）
UPDATE public.haunted_houses
SET country = CASE
  WHEN lng >= 122.8 OR city ~ '(都|道|府|県)$' THEN 'JP'
  ELSE 'TW'
END
WHERE country IS NULL OR country NOT IN ('TW', 'JP');

-- 3. 建立標準化別名檢視表 public.cases（支援直接以 cases 查詢與寫入）
CREATE OR REPLACE VIEW public.cases AS
SELECT
  id,
  country,
  city,
  district,
  address,
  doorplate_address,
  lat,
  lng,
  incident_date,
  category,
  reason AS summary,
  reason,
  source AS source_name,
  source,
  source_title,
  source_url,
  media_verification,
  auction_record,
  history_timeline,
  verification_status,
  location_accuracy,
  verification_score,
  case_fingerprint,
  source_type,
  db_source,
  building_type,
  current_status,
  merged_count,
  collected_at,
  updated_at,
  created_at
FROM public.haunted_houses;

-- 4. 建立案件多來源證據表：public.case_sources
-- 同一案件若有多家新聞媒體、法院判決或法拍公告報導，只會在主表保留 1 筆案件，並將所有原始來源記錄於此表
CREATE TABLE IF NOT EXISTS public.case_sources (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id BIGINT NOT NULL REFERENCES public.haunted_houses(id) ON DELETE CASCADE,
  country TEXT NOT NULL DEFAULT 'TW' CHECK (country IN ('TW', 'JP')),
  source_name TEXT NOT NULL,                       -- 媒體或機構名稱（如：聯合新聞網、司法院法拍公告、読売新聞）
  source_type TEXT NOT NULL DEFAULT 'news',        -- news / judicial_judgment / judicial_auction / government_open_data
  source_title TEXT NOT NULL,                      -- 原始新聞標題或裁判書案由
  source_url TEXT NOT NULL UNIQUE,                 -- 原始網址（唯一鍵，防止同一篇報導重複入庫）
  published_date TEXT,                             -- 報導發布或裁判日期 (YYYY-MM-DD)
  raw_excerpt TEXT DEFAULT '',                     -- 原始報導關鍵段落摘錄
  collected_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_case_sources_case_id ON public.case_sources (case_id);
CREATE INDEX IF NOT EXISTS idx_case_sources_country_date ON public.case_sources (country, published_date DESC);

-- 5. 建立待查證案件隔離表：public.pending_cases
-- 凡無法確認具體路段／町丁地址、僅提及模糊社區名稱而無棟別佐證、或待確認是否為專有部分非自然死亡之案件，一律存入此表，不直接公開
CREATE TABLE IF NOT EXISTS public.pending_cases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  country TEXT NOT NULL DEFAULT 'TW' CHECK (country IN ('TW', 'JP')),
  city TEXT DEFAULT '',
  district TEXT DEFAULT '',
  raw_location_text TEXT DEFAULT '',               -- 新聞中抽取出之原始未確認地點描述
  standardized_address TEXT DEFAULT '',            -- 初步標準化地址（若有）
  incident_date TEXT DEFAULT '',
  category TEXT DEFAULT '待查證事故',
  summary TEXT NOT NULL,                           -- AI 擷取之案情摘要
  source_name TEXT NOT NULL,
  source_title TEXT NOT NULL,
  source_url TEXT NOT NULL UNIQUE,                 -- 原始文章網址（唯一鍵）
  pending_reason TEXT NOT NULL,                    -- 進入待查證之原因（如：ADDRESS_TOO_VAGUE / COMMUNITY_ONLY / NON_RESIDENTIAL_SUSPECTED）
  ai_confidence NUMERIC(4,2) DEFAULT 0.50,         -- AI 地址與事故精確度信心分數 (0.00 ~ 1.00)
  raw_payload JSONB DEFAULT '{}'::jsonb,           -- 完整擷取 JSON 備份
  review_status TEXT NOT NULL DEFAULT 'pending' CHECK (review_status IN ('pending', 'approved', 'rejected')),
  collected_at TIMESTAMPTZ DEFAULT NOW(),
  reviewed_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_pending_cases_status_country ON public.pending_cases (review_status, country, collected_at DESC);

-- 6. 建立爬蟲執行紀錄表：public.crawl_logs
CREATE TABLE IF NOT EXISTS public.crawl_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id TEXT NOT NULL,                            -- 執行批次 UUID 或 GitHub Action Run ID
  country TEXT NOT NULL CHECK (country IN ('TW', 'JP', 'ALL')),
  crawl_mode TEXT NOT NULL DEFAULT 'incremental',  -- incremental (定期增量) / historical_backfill (歷史回溯)
  sources_queried JSONB DEFAULT '[]'::jsonb,       -- 本次查詢之資料來源清單
  articles_fetched INTEGER DEFAULT 0,              -- 抓取之原始文章／公告總數
  cases_inserted INTEGER DEFAULT 0,                -- 新增通過查證之案件數
  sources_linked INTEGER DEFAULT 0,                -- 新增關聯至 case_sources 之證據數
  pending_saved INTEGER DEFAULT 0,                 -- 移入 pending_cases 待查證之案件數
  duplicates_merged INTEGER DEFAULT 0,             -- 自動辨識並合併之重複報導數
  status TEXT NOT NULL DEFAULT 'running',          -- running / completed / failed
  error_message TEXT DEFAULT '',
  started_at TIMESTAMPTZ DEFAULT NOW(),
  finished_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_crawl_logs_started_at ON public.crawl_logs (started_at DESC);

-- 7. 資料庫層級真實性約束：確保主表每筆公開案件皆具備真實 http/https 連結
ALTER TABLE public.haunted_houses DROP CONSTRAINT IF EXISTS chk_verified_real_http_url;
ALTER TABLE public.haunted_houses
  ADD CONSTRAINT chk_verified_real_http_url
  CHECK (source_url ~* '^https?://[^\s]+\.[^\s]+');

-- 8. 建立高速檢索索引
CREATE INDEX IF NOT EXISTS idx_haunted_houses_country_city_dist
  ON public.haunted_houses (country, city, district, incident_date DESC);

CREATE INDEX IF NOT EXISTS idx_haunted_houses_fingerprint
  ON public.haunted_houses (case_fingerprint);

CREATE INDEX IF NOT EXISTS idx_haunted_houses_lat_lng
  ON public.haunted_houses (lat, lng);

CREATE INDEX IF NOT EXISTS idx_haunted_houses_cjk_trgm_search
  ON public.haunted_houses
  USING GIN (
    (
      COALESCE(city, '') || ' ' ||
      COALESCE(district, '') || ' ' ||
      COALESCE(doorplate_address, '') || ' ' ||
      COALESCE(address, '') || ' ' ||
      COALESCE(reason, '') || ' ' ||
      COALESCE(source, '')
    ) gin_trgm_ops
  );

-- 9. 設定 Row Level Security (RLS) 安全性權限
-- (A) 主表 haunted_houses 與證據表 case_sources：開放公開唯讀，僅限後端 service_role 寫入
ALTER TABLE public.haunted_houses ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow public read verified cases" ON public.haunted_houses;
CREATE POLICY "Allow public read verified cases"
  ON public.haunted_houses
  FOR SELECT
  USING (source_url ~* '^https?://');

ALTER TABLE public.case_sources ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow public read case sources" ON public.case_sources;
CREATE POLICY "Allow public read case sources"
  ON public.case_sources
  FOR SELECT
  USING (true);

-- (B) 待查證表 pending_cases 與爬蟲日誌 crawl_logs：禁止未授權公開讀取，僅限 service_role 存取
ALTER TABLE public.pending_cases ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Service role full access pending_cases" ON public.pending_cases;
CREATE POLICY "Service role full access pending_cases"
  ON public.pending_cases
  FOR ALL
  USING (auth.role() = 'service_role');

ALTER TABLE public.crawl_logs ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Service role full access crawl_logs" ON public.crawl_logs;
CREATE POLICY "Service role full access crawl_logs"
  ON public.crawl_logs
  FOR ALL
  USING (auth.role() = 'service_role');
