-- =============================================================================
-- 台灣 22 縣市 + 日本 47 都道府縣 跨國歷年事故建物與實證資料庫 (Supabase PostgreSQL)
-- 檔案：supabase_schema.sql
-- 核心設計：嚴格資料真實性驗證系統（Anti-Hallucination & Two-Stage Verification Pipeline）
-- 包含四大核心資料表與檢視表：
--   1. public.pending_cases  (第一階段緩衝與審核表：所有爬蟲與 Gemini 分析結果一律先寫入此表，不直接公開)
--   2. public.haunted_houses (第二階段正式公開表：僅限通過決定論證據查核 verification_status='verified' 之案件寫入)
--   3. public.cases          (與 public.haunted_houses 雙向相容之標準化別名檢視表，含完整 12 項必填證據欄位)
--   4. public.case_sources   (一對多案件原始新聞／判決／法拍證據來源表，支援跨媒體同案件歸戶合併)
--   5. public.crawl_logs     (自動化爬蟲與品質檢查執行紀錄表)
-- =============================================================================

-- 1. 啟用 PostgreSQL 高速字串相似度與中日文 Trigram 檢索擴充套件
