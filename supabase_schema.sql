-- 9. 設定嚴格 Row Level Security (RLS) 安全性權限
-- (A) 正式表 haunted_houses 與證據表 case_sources：
--     前端 anon/authenticated 僅有唯讀權限，且僅能讀取 verification_status 為 verified 且在建物內之案件；
--     嚴禁任何公開金鑰或未經驗證程序直接 INSERT / UPDATE / DELETE 正式表。
-- (B) 緩衝審核表 pending_cases 與爬蟲日誌 crawl_logs：
--     全面封鎖公開讀取與寫入，僅限後端驗證程序 (service_role) 存取。
-- =============================================================================
ALTER TABLE public.haunted_houses ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow public read verified cases" ON public.haunted_houses;
CREATE POLICY "Allow public read verified cases"
  ON public.haunted_houses
  FOR SELECT
  USING (
    source_url ~* '^https?://'
    AND verification_status IN ('verified', 'multi_source_verified')
    AND location_description = 'inside_building'
  );

DROP POLICY IF EXISTS "Service role write verified cases only" ON public.haunted_houses;
CREATE POLICY "Service role write verified cases only"
  ON public.haunted_houses
  FOR ALL
  USING (auth.role() = 'service_role')
  WITH CHECK (
    auth.role() = 'service_role'
    AND verification_status IN ('verified', 'multi_source_verified')
    AND location_description = 'inside_building'
    AND length(trim(address_evidence)) >= 4
    AND length(trim(incident_evidence)) >= 6
  );

ALTER TABLE public.case_sources ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Allow public read case sources" ON public.case_sources;
CREATE POLICY "Allow public read case sources"
  ON public.case_sources
  FOR SELECT
  USING (true);

DROP POLICY IF EXISTS "Service role write case sources" ON public.case_sources;
CREATE POLICY "Service role write case sources"
  ON public.case_sources
  FOR ALL
  USING (auth.role() = 'service_role')
  WITH CHECK (auth.role() = 'service_role');

ALTER TABLE public.pending_cases ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Service role full access pending_cases" ON public.pending_cases;
CREATE POLICY "Service role full access pending_cases"
  ON public.pending_cases
  FOR ALL
  USING (auth.role() = 'service_role')
  WITH CHECK (auth.role() = 'service_role');

