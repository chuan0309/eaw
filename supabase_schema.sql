-- =============================================================================
-- 2. 第一階段隔離與驗證緩衝表：public.pending_cases
-- 所有新蒐集與 Gemini 抽取之案件必須先寫入 pending_cases，嚴禁 AI 直接寫入正式表！
-- =============================================================================
CREATE TABLE IF NOT EXISTS public.pending_cases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- 12 個強制證據與驗證欄位
  source_url TEXT NOT NULL UNIQUE,                 -- 爬蟲實際取得之原始網址（嚴禁 AI 生成或修改）
  source_title TEXT NOT NULL,                      -- 爬蟲實際取得之原始文章標題
  source_name TEXT NOT NULL,                       -- 資料來源媒體或政府／法院機構名稱
  source_published_date TEXT DEFAULT '',           -- 原始文章發布日期 (YYYY-MM-DD)
  incident_date TEXT DEFAULT '',                   -- 事故發生日期（必須有內文證據支持，禁止推論）
  incident_type TEXT DEFAULT '待查證事故',           -- 刑事命案 / 輕生事故 / 意外身亡 / 其他非自然死亡 / 法拍與其他
  country TEXT NOT NULL DEFAULT 'TW' CHECK (country IN ('TW', 'JP')),
  address TEXT DEFAULT '',                         -- 標準化後之地址（不補全原文未記載之資訊）
  address_evidence TEXT DEFAULT '',                -- 原始文章中可逐字找到的地址依據原文片段
  incident_evidence TEXT DEFAULT '',               -- 原始文章中可逐字找到的事故依據原文片段
  location_description TEXT NOT NULL DEFAULT 'unknown'
    CHECK (location_description IN ('inside_building', 'outside_building', 'nearby', 'unknown')),
  verification_status TEXT NOT NULL DEFAULT 'pending'
    CHECK (verification_status IN ('pending', 'verified', 'rejected')),

  -- 輔助行政區與審核診斷欄位
  city TEXT DEFAULT '',                            -- 台灣縣市 或 日本都道府縣
  district TEXT DEFAULT '',                        -- 台灣行政區 或 日本市區町村
  raw_location_text TEXT DEFAULT '',               -- 原始抽取未標準化地點文字
  standardized_address TEXT DEFAULT '',            -- 標準化門牌／町丁番地
  lat DOUBLE PRECISION DEFAULT 0.0,
  lng DOUBLE PRECISION DEFAULT 0.0,
  location_accuracy TEXT DEFAULT 'UNVERIFIED',
  category TEXT DEFAULT '待查證事故',
  summary TEXT NOT NULL DEFAULT '',
  pending_reason TEXT NOT NULL DEFAULT 'AWAITING_VERIFICATION',
  rejection_reason TEXT DEFAULT '',
  ai_confidence NUMERIC(4,2) DEFAULT 0.00,         -- 僅供紀錄參考，嚴禁作為 verified 判定依據
  quality_check_report JSONB DEFAULT '{}'::jsonb,  -- 自動品質檢查 9 項結果完整報告
  raw_payload JSONB DEFAULT '{}'::jsonb,
