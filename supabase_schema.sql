-- =============================================================================
-- 7. 決定論晉升預存程序：public.promote_verified_case(p_pending_id BIGINT)
-- 強制規則：所有案件必須先存在於 pending_cases，且通過：
--   (1) verification_status = 'verified'
--   (2) location_description = 'inside_building'
--   (3) address_evidence 與 incident_evidence 皆非空字串
--   (4) 座標有效（lat != 0 且 lng != 0）
-- 始得寫入正式表 haunted_houses (cases)
-- =============================================================================
CREATE OR REPLACE FUNCTION public.promote_verified_case(p_pending_id BIGINT)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  v_rec public.pending_cases%ROWTYPE;
  v_case_id BIGINT;
BEGIN
  SELECT * INTO v_rec FROM public.pending_cases WHERE id = p_pending_id;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'pending_case id % does not exist', p_pending_id;
  END IF;

  IF v_rec.verification_status <> 'verified' THEN
    RAISE EXCEPTION 'Cannot promote case %: verification_status is %, expected verified', p_pending_id, v_rec.verification_status;
  END IF;

  IF v_rec.location_description <> 'inside_building' THEN
    RAISE EXCEPTION 'Cannot promote case %: location_description is %, expected inside_building', p_pending_id, v_rec.location_description;
  END IF;

  IF COALESCE(LENGTH(TRIM(v_rec.address_evidence)), 0) < 4 OR COALESCE(LENGTH(TRIM(v_rec.incident_evidence)), 0) < 6 THEN
    RAISE EXCEPTION 'Cannot promote case %: missing verbatim address_evidence or incident_evidence', p_pending_id;
  END IF;

  IF COALESCE(v_rec.lat, 0.0) = 0.0 OR COALESCE(v_rec.lng, 0.0) = 0.0 THEN
    RAISE EXCEPTION 'Cannot promote case %: unverified coordinates', p_pending_id;
  END IF;

  INSERT INTO public.haunted_houses (
    country, city, district, address, doorplate_address, lat, lng,
    incident_date, incident_type, category, reason,
    source, source_name, source_url, source_title, source_published_date,
    address_evidence, incident_evidence, location_description,
    verification_status, location_accuracy, case_fingerprint, quality_check_report
  ) VALUES (
    v_rec.country, v_rec.city, v_rec.district, v_rec.address, v_rec.standardized_address, v_rec.lat, v_rec.lng,
    v_rec.incident_date, v_rec.incident_type, v_rec.incident_type, v_rec.summary,
    v_rec.source_name, v_rec.source_name, v_rec.source_url, v_rec.source_title, v_rec.source_published_date,
    v_rec.address_evidence, v_rec.incident_evidence, v_rec.location_description,
    'verified', v_rec.location_accuracy, v_rec.case_fingerprint, v_rec.quality_check_report
  )
  ON CONFLICT (address) DO UPDATE SET
    merged_count = public.haunted_houses.merged_count + 1,
    verification_status = 'multi_source_verified',
    updated_at = NOW()
  RETURNING id INTO v_case_id;

  INSERT INTO public.case_sources (
    case_id, country, source_name, source_title, source_url,
    published_date, address_evidence, incident_evidence, raw_excerpt
  ) VALUES (
    v_case_id, v_rec.country, v_rec.source_name, v_rec.source_title, v_rec.source_url,
    v_rec.source_published_date, v_rec.address_evidence, v_rec.incident_evidence, v_rec.summary
  )
  ON CONFLICT (source_url) DO NOTHING;

  UPDATE public.pending_cases
  SET review_status = 'approved', reviewed_at = NOW()
  WHERE id = p_pending_id;

  RETURN v_case_id;
END;
$$;

