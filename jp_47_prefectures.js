  for (const [key, coords] of Object.entries(TAIWAN_STREET_CORRIDOR_COORDS)) {
    const [kCity, kDist, kRoad] = key.split("_");
    if (kCity === c && kDist === d && norm.includes(kRoad)) {
      let h1 = 2166136261, h2 = 16777619;
      const s = `${norm}_${seedStr}`;
      for (let i = 0; i < s.length; i++) {
        const ch = s.charCodeAt(i);
        h1 = Math.imul(h1 ^ ch, 16777619);
        h2 = Math.imul(h2 ^ (ch * 31), 2166136261);
      }
      const dLat = ((((h1 >>> 0) % 1000) - 500) / 1000) * 0.0012;
      const dLng = ((((h2 >>> 0) % 1000) - 500) / 1000) * 0.0012;
      return [Number((coords[0] + dLat).toFixed(6)), Number((coords[1] + dLng).toFixed(6)), true];
    }
  }

  // 2. Fallback to township coordinates with slight street-scale offset
  const [tLat, tLng] = getTaiwanTownshipCoords(c, d);
